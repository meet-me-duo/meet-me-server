package com.meetme.server.coordination.domain.analysis

import com.meetme.server.coordination.domain.matching.IrAlternativeChoice
import com.meetme.server.meetingroom.domain.MeetingMode
import com.meetme.server.submission.domain.ir.IrInputBinding
import com.meetme.server.submission.domain.ir.IrInterpretation
import com.meetme.server.submission.domain.ir.IrSourceBinding
import com.meetme.server.submission.domain.ir.IrSourceKind
import com.meetme.server.submission.domain.ir.ScheduleIrContext
import org.junit.jupiter.api.DynamicTest.dynamicTest
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.TestFactory
import java.util.UUID
import kotlin.test.assertEquals
import kotlin.test.assertNotEquals
import kotlin.test.assertTrue
import com.meetme.server.support.FinalAnalysisRouteTestFixture as F

/** Unit A spec properties; expected bytes are not generated by the fingerprint implementation. */
class FinalAnalysisRouteIdentityTest {
    @Test
    fun `FAR01 default legacy identity differs from explicitly selected DSL`() {
        val legacy = F.route(FinalAnalysisRouteChoice.Legacy)
        assertNotEquals(legacy.fingerprint(), F.route().fingerprint())
        assertTrue(legacy.fingerprint().matches(Regex("[a-f0-9]{64}")))
    }

    @Test
    fun `FAR02 selected time is immutable audit metadata outside identity`() {
        val route = F.route()
        assertEquals(route.fingerprint(), route.copy(selectedAt = route.selectedAt.plusSeconds(3600)).fingerprint())
    }

    @Test
    fun `FAR03 policy collections are canonical despite insertion order`() {
        val choice = F.choice()
        val a = IrAlternativeChoice(F.ir.first, "synthetic-group-a", "option-one")
        val b = IrAlternativeChoice(F.ir.second, "synthetic-group-b", "option-two")
        val first =
            choice.copy(
                policy =
                    choice.policy.copy(
                        eligibleInterpretations = linkedSetOf(IrInterpretation.EXPLICIT, IrInterpretation.INFERRED),
                        alternativeChoices = listOf(a, b),
                    ),
            )
        val second =
            choice.copy(
                policy =
                    choice.policy.copy(
                        eligibleInterpretations = linkedSetOf(IrInterpretation.INFERRED, IrInterpretation.EXPLICIT),
                        alternativeChoices = listOf(b, a),
                    ),
            )
        assertEquals(F.route(first).fingerprint(), F.route(second).fingerprint())
    }

    @Test
    fun `FAR04 adjacent policy strings cannot collide through concatenation`() {
        val choice = F.choice()

        fun selected(
            group: String,
            alternative: String,
        ) = F.route(
            choice.copy(
                policy =
                    choice.policy.copy(
                        alternativeChoices = listOf(IrAlternativeChoice(F.ir.first, group, alternative)),
                    ),
            ),
        )
        assertNotEquals(selected("synthetic-a", "bc").fingerprint(), selected("synthetic-ab", "c").fingerprint())
    }

    @TestFactory
    fun `FAR05 all frozen identities and native provenance affect the fingerprint`() =
        run {
            val route = F.route()
            val choice = F.choice()
            val context = choice.context
            val input = context.inputs.first()
            val source = input.sources.first()

            fun fromChoice(value: FinalAnalysisRouteChoice.DslContextV2) = route.copy(choice = value)

            fun fromContext(value: ScheduleIrContext) = fromChoice(choice.copy(context = value))

            fun fromInput(value: IrInputBinding) = fromContext(context.copy(inputs = listOf(value) + context.inputs.drop(1)))

            fun fromSource(value: IrSourceBinding) = fromInput(input.copy(sources = listOf(value) + input.sources.drop(1)))
            val variants =
                linkedMapOf(
                    "route run" to route.copy(runId = UUID(0, 9801)),
                    "route batch" to route.copy(batchId = UUID(0, 9802)),
                    "route room" to route.copy(roomId = UUID(0, 9803)),
                    "response contract" to
                        fromChoice(choice.copy(identity = choice.identity.copy(responseContractVersion = "synthetic-next"))),
                    "semantic contract" to fromChoice(choice.copy(identity = choice.identity.copy(irSemanticVersion = "synthetic-next"))),
                    "policy identity" to fromChoice(choice.copy(identity = choice.identity.copy(policyVersion = "synthetic-next"))),
                    "meeting mode" to fromChoice(choice.copy(meetingMode = MeetingMode.IN_PERSON)),
                    "policy version" to fromChoice(choice.copy(policy = choice.policy.copy(version = "synthetic-next"))),
                    "eligible interpretations" to
                        fromChoice(
                            choice.copy(
                                policy = choice.policy.copy(eligibleInterpretations = setOf(IrInterpretation.INFERRED)),
                            ),
                        ),
                    "unconstrained selection" to fromChoice(choice.copy(policy = choice.policy.copy(allowExplicitUnconstrained = true))),
                    "context run" to fromContext(context.copy(runId = UUID(0, 9811))),
                    "context batch" to fromContext(context.copy(batchId = UUID(0, 9812))),
                    "context room" to fromContext(context.copy(roomId = UUID(0, 9813))),
                    "zone" to fromContext(context.copy(timeZone = "UTC")),
                    "search start" to fromContext(context.copy(searchStart = context.searchStart.plusDays(1))),
                    "search end" to fromContext(context.copy(searchEnd = context.searchEnd.plusDays(1))),
                    "context policy" to fromContext(context.copy(policyVersion = "synthetic-next")),
                    "input membership" to fromContext(context.copy(inputs = context.inputs.dropLast(1))),
                    "submission version" to fromInput(input.copy(submissionVersionId = UUID(0, 9821))),
                    "participant owner" to fromInput(input.copy(participantId = UUID(0, 9822))),
                    "submission revision" to fromInput(input.copy(submissionRevision = input.submissionRevision + 1)),
                    "original revision" to fromInput(input.copy(originalRevision = (input.originalRevision ?: 0) + 1)),
                    "input content" to fromInput(input.copy(contentSha256 = "a".repeat(64))),
                    "source membership" to fromInput(input.copy(sources = input.sources.dropLast(1))),
                    "source identity" to fromSource(source.copy(sourceId = "synthetic-other")),
                    "source kind" to fromSource(source.copy(kind = IrSourceKind.SUPPLEMENT)),
                    "source revision" to fromSource(source.copy(revision = source.revision + 1)),
                    "source length" to fromSource(source.copy(codePointLength = source.codePointLength + 1)),
                    "source digest" to fromSource(source.copy(contentSha256 = "b".repeat(64))),
                    "source reference time" to fromSource(source.copy(referenceAt = source.referenceAt.plusSeconds(1))),
                    "source question" to fromSource(source.copy(questionId = UUID(0, 9823))),
                    "source original start" to fromSource(source.copy(originalStartCodePoint = 1)),
                    "source original end" to fromSource(source.copy(originalEndCodePoint = 2)),
                )
            variants.map { (name, changed) -> dynamicTest(name) { assertNotEquals(route.fingerprint(), changed.fingerprint()) } }
        }
}
