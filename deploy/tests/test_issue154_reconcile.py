"""Issue154 read-only recovery: observation must not become another deployment.

These are independent wire fixtures, not records generated by the implementation.
No AWS, provider, shell or database process is invoked.
"""
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import unittest


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("issue154_readonly_reconcile", ROOT / "pipeline/release_pipeline.py")
PIPELINE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(PIPELINE)
RULES = ("meet-me-production-db-credential-reconcile", "meet-me-production-db-credential-rotated")
COMMAND = "00000000-0000-4000-8000-000000000154"
SENTINEL = "synthetic-secret-that-must-not-enter-a-report"


def original_identity():
    source = "a" * 40
    return {"sourceSha": source, "buildRunId": "154", "buildRunAttempt": "1",
            "workflowRunId": "155", "workflowRunAttempt": "2", "releaseId": source + "-154-1",
            "imageDigest": "sha256:" + "b" * 64}


def current_identity():
    return original_identity() | {"workflowRunId": "999", "workflowRunAttempt": "3"}


def operation_id(bound):
    return hashlib.sha256(json.dumps(bound, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()


def journal(protocol="transition", command_id=COMMAND):
    bound = original_identity()
    common = {"identity": bound, "operationId": operation_id(bound), "sequence": 8,
              "deploymentState": "UNKNOWN", "commandId": command_id,
              "originalRules": {name: "ENABLED" for name in RULES},
              "outcome": "RECOVERY_REQUIRED", "rulesState": "PAUSED"}
    if protocol == "automatic":
        return common | {"protocol": "meet-me-automatic-operation-v1", "rulesState": "UNTOUCHED"}
    return common | {"protocol": "meet-me-transition-operation-v1", "action": "deploy",
                     "phase": "RECOVERY", "changedRules": list(RULES), "reason": "COMMAND_UNCONFIRMED"}


class ReadOnlyAdapter:
    def __init__(self, record=None):
        self.record = journal() if record is None else record
        self.events = []
        self.status = "Success"
        self.payload = {"sourceSha": original_identity()["sourceSha"], "phase": "READY",
                        "imageMatches": True, "historyMatches": True}
        self.host_verified = True
        self.rules = {name: "ENABLED" for name in RULES}
        self.pending = 0
        self.read_error = None
        self.query_error = None
        self.host_error = None
        self.rules_error = None
        self.pending_error = None
        self.reply = None

    def read_operation_for_reconcile(self, op_id):
        self.events.append(("read_journal", op_id))
        if self.read_error is not None:
            raise self.read_error
        return copy.deepcopy(self.record)

    def command_result(self, command_id):
        self.events.append(("query_command", command_id))
        if self.query_error is not None:
            raise self.query_error
        return copy.deepcopy(self.reply if self.reply is not None else {"status": self.status, "result": self.payload})

    def verify_host(self, payload):
        self.events.append(("verify_host",))
        if self.host_error is not None:
            raise self.host_error
        return self.host_verified

    def read_rules(self):
        self.events.append(("read_rules",))
        if self.rules_error is not None:
            raise self.rules_error
        return copy.deepcopy(self.rules)

    def active_commands(self):
        self.events.append(("read_pending",))
        if self.pending_error is not None:
            raise self.pending_error
        return self.pending

    def __getattr__(self, name):
        if name in {"claim_operation", "owns_operation", "load_operation", "save_operation",
                    "write_rule", "submit_deploy", "release_operation", "rollback", "cancel_command"}:
            def forbidden(*_args, **_kwargs):
                self.events.append(("FORBIDDEN", name))
                raise AssertionError("Read-only recovery attempted a write or ownership path")
            return forbidden
        raise AttributeError(name)


class Issue154ReadOnlyReconciliationTests(unittest.TestCase):
    def invoke(self, adapter, bound=None, op_id=None):
        try:
            return PIPELINE.reconcile_known_operation(
                current_identity() if bound is None else bound,
                operation_id(original_identity()) if op_id is None else op_id,
                adapter,
            )
        finally:
            self.assertFalse([event for event in adapter.events if event[0] == "FORBIDDEN"])

    def assert_report(self, report):
        self.assertEqual("meet-me-release-reconciliation-v1", report["protocol"])
        self.assertEqual(original_identity(), report["identity"])
        self.assertEqual(operation_id(original_identity()), report["operationId"])
        self.assertIs(False, report["deploymentComplete"])
        self.assertEqual("RECOVERY_REQUIRED", report["outcome"])
        self.assertIs(type(report["hostVerified"]), bool)
        self.assertNotIn(SENTINEL, json.dumps(report))

    def test_bound_known_command_is_observed_without_releasing_or_claiming_completion(self):
        adapter = ReadOnlyAdapter()
        original = copy.deepcopy(adapter.record)
        report = self.invoke(adapter)
        self.assert_report(report)
        self.assertEqual("Success", report["commandStatus"])
        self.assertIs(True, report["hostVerified"])
        self.assertEqual(adapter.rules, report["rulesObserved"])
        self.assertEqual(0, report["pendingCommands"])
        self.assertEqual([("query_command", COMMAND)], [e for e in adapter.events if e[0] == "query_command"])
        self.assertEqual(original, adapter.record)

    def test_automatic_and_transition_journals_share_the_read_only_candidate_binding(self):
        for protocol in ("automatic", "transition"):
            adapter = ReadOnlyAdapter(journal(protocol))
            with self.subTest(protocol=protocol):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertEqual("Success", report["commandStatus"])

    def test_original_execution_identity_is_retained_across_a_new_recovery_run(self):
        adapter = ReadOnlyAdapter()
        report = self.invoke(adapter, bound=current_identity())
        self.assert_report(report)
        self.assertNotEqual(current_identity()["workflowRunId"], report["identity"]["workflowRunId"])

    def test_missing_command_id_is_unknown_without_query_or_state_change(self):
        for protocol in ("automatic", "transition"):
            adapter = ReadOnlyAdapter(journal(protocol, command_id=None))
            with self.subTest(protocol=protocol):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertEqual("UNKNOWN", report["commandStatus"])
                self.assertIs(False, report["hostVerified"])
                self.assertFalse([e for e in adapter.events if e[0] in {"query_command", "verify_host"}])

    def test_query_failure_stays_unknown_and_does_not_expose_exception_text(self):
        adapter = ReadOnlyAdapter()
        adapter.query_error = TimeoutError(SENTINEL)
        report = self.invoke(adapter)
        self.assert_report(report)
        self.assertEqual("UNKNOWN", report["commandStatus"])
        self.assertIs(False, report["hostVerified"])
        self.assertEqual(1, sum(e[0] == "query_command" for e in adapter.events))

    def test_non_success_statuses_are_observations_not_permission_to_resume(self):
        for status in ("Pending", "InProgress", "Delayed", "Failed", "Cancelled", "TimedOut", "Cancelling"):
            adapter = ReadOnlyAdapter()
            adapter.status = status
            with self.subTest(status=status):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertEqual(status, report["commandStatus"])
                self.assertIs(False, report["hostVerified"])

    def test_success_requires_fresh_literal_boolean_host_proof(self):
        for value in (False, 1, "true", None):
            adapter = ReadOnlyAdapter()
            adapter.host_verified = value
            with self.subTest(hostVerified=value):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertIs(False, report["hostVerified"])
                self.assertEqual(1, sum(e[0] == "verify_host" for e in adapter.events))
        adapter = ReadOnlyAdapter()
        adapter.host_error = OSError(SENTINEL)
        report = self.invoke(adapter)
        self.assert_report(report)
        self.assertIs(False, report["hostVerified"])

    def test_stored_success_with_foreign_source_or_nonready_host_is_not_verified(self):
        for payload in (None, [], {"sourceSha": "f" * 40, "phase": "READY"},
                        {"sourceSha": original_identity()["sourceSha"], "phase": "V8_STARTED"}):
            adapter = ReadOnlyAdapter()
            adapter.payload = payload
            with self.subTest(payload=payload):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertIs(False, report["hostVerified"])

    def test_malformed_command_reply_is_unknown_without_leaking_unvalidated_payload(self):
        for reply in ({}, {"status": SENTINEL, "result": {"secret": SENTINEL}},
                      {"status": "Success", "result": {}, "extra": SENTINEL}, []):
            adapter = ReadOnlyAdapter()
            adapter.reply = reply
            with self.subTest(reply=reply):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertEqual("UNKNOWN", report["commandStatus"])
                self.assertIs(False, report["hostVerified"])

    def test_rule_and_pending_read_failures_are_explicitly_unknown(self):
        adapter = ReadOnlyAdapter()
        adapter.rules_error = OSError(SENTINEL)
        adapter.pending_error = OSError(SENTINEL)
        report = self.invoke(adapter)
        self.assert_report(report)
        self.assertIsNone(report["rulesObserved"])
        self.assertIsNone(report["pendingCommands"])

    def test_untrusted_rule_values_and_pending_types_are_not_reported_as_verified(self):
        bad_rules = ({}, {RULES[0]: "ENABLED"}, {name: True for name in RULES},
                     {name: SENTINEL for name in RULES}, {**{name: "ENABLED" for name in RULES}, "extra": SENTINEL})
        for rules in bad_rules:
            adapter = ReadOnlyAdapter()
            adapter.rules = rules
            with self.subTest(rules=rules):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertIsNone(report["rulesObserved"])
        for pending in (True, -1, "0", None):
            adapter = ReadOnlyAdapter()
            adapter.pending = pending
            with self.subTest(pending=pending):
                report = self.invoke(adapter)
                self.assert_report(report)
                self.assertIsNone(report["pendingCommands"])

    def test_positive_pending_and_paused_rules_remain_visible_but_never_complete(self):
        adapter = ReadOnlyAdapter()
        adapter.rules[RULES[0]] = "DISABLED"
        adapter.pending = 2
        report = self.invoke(adapter)
        self.assert_report(report)
        self.assertEqual(2, report["pendingCommands"])
        self.assertEqual(adapter.rules, report["rulesObserved"])

    def test_bad_current_identity_or_operation_id_fails_before_query(self):
        bad_bound = [current_identity() | {"extra": "field"}, current_identity() | {"workflowRunAttempt": 2},
                     current_identity() | {"sourceSha": "bad"}]
        for bound in bad_bound:
            adapter = ReadOnlyAdapter()
            with self.subTest(bound=bound), self.assertRaises(ValueError):
                self.invoke(adapter, bound=bound)
            self.assertFalse([e for e in adapter.events if e[0] == "query_command"])
        for op_id in ("", "x" * 64, "F" * 64, "f" * 64, 154, None):
            adapter = ReadOnlyAdapter()
            actual = None if op_id is None else op_id
            with self.subTest(opId=op_id), self.assertRaises(ValueError):
                PIPELINE.reconcile_known_operation(current_identity(), actual, adapter)
            self.assertFalse([e for e in adapter.events if e[0] in {"query_command", "FORBIDDEN"}])

    def test_foreign_candidate_cannot_be_reconciled_even_with_a_valid_identity_hash(self):
        mutations = ({"sourceSha": "c" * 40, "releaseId": "c" * 40 + "-154-1"},
                     {"buildRunId": "777", "releaseId": "a" * 40 + "-777-1"},
                     {"buildRunAttempt": "9", "releaseId": "a" * 40 + "-154-9"},
                     {"imageDigest": "sha256:" + "d" * 64})
        for mutation in mutations:
            record = journal()
            record["identity"].update(mutation)
            record["operationId"] = operation_id(record["identity"])
            adapter = ReadOnlyAdapter(record)
            with self.subTest(mutation=mutation), self.assertRaises(ValueError):
                self.invoke(adapter, op_id=record["operationId"])
            self.assertFalse([e for e in adapter.events if e[0] == "query_command"])

    def test_forged_or_malformed_journal_is_rejected_before_any_command_query(self):
        mutations = ({"protocol": "untrusted"}, {"operationId": "f" * 64}, {"sequence": True},
                     {"commandId": SENTINEL}, {"commandId": ""}, {"extra": "field"},
                     {"originalRules": {}}, {"deploymentState": []}, {"rulesState": {}},
                     {"identity": original_identity() | {"workflowRunId": "888"}})
        for protocol in ("automatic", "transition"):
            for mutation in mutations:
                adapter = ReadOnlyAdapter(journal(protocol) | mutation)
                with self.subTest(protocol=protocol, mutation=mutation):
                    with self.assertRaises(ValueError):
                        self.invoke(adapter)
                    self.assertFalse([e for e in adapter.events if e[0] == "query_command"])

    def test_missing_or_unreadable_journal_does_not_invent_an_operation(self):
        adapter = ReadOnlyAdapter()
        adapter.record = None
        with self.assertRaises(ValueError):
            self.invoke(adapter)
        adapter = ReadOnlyAdapter()
        adapter.read_error = OSError(SENTINEL)
        with self.assertRaises((OSError, ValueError)):
            self.invoke(adapter)
        self.assertFalse([e for e in adapter.events if e[0] == "query_command"])

    def test_impossible_journal_command_state_pairs_are_rejected_before_query(self):
        for protocol in ("automatic", "transition"):
            for mutation in ({"deploymentState": "NOT_ATTEMPTED", "commandId": COMMAND},
                             {"deploymentState": "APPLIED", "commandId": None}):
                adapter = ReadOnlyAdapter(journal(protocol) | mutation)
                with self.subTest(protocol=protocol, mutation=mutation):
                    with self.assertRaises(ValueError):
                        self.invoke(adapter)
                    self.assertFalse([e for e in adapter.events if e[0] == "query_command"])


if __name__ == "__main__":
    unittest.main()
